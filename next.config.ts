import type { NextConfig } from 'next';

const isProd = process.env.NODE_ENV === 'production';

if (isProd && !process.env.NEXT_PUBLIC_SITE_URL) {
  console.warn('⚠ NEXT_PUBLIC_SITE_URL is not set: canonical URLs, sitemap and Open Graph tags will use http://localhost:3000.');
}

// Static-compatible policy (no nonces, so pages stay prerendered). Next.js
// injects inline bootstrap scripts, hence 'unsafe-inline' for scripts.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "media-src 'self'",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

const securityHeaders = [
  { key: 'Content-Security-Policy', value: csp },
  { key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains; preload' },
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'X-Frame-Options', value: 'DENY' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=(), interest-cohort=()' },
];

const immutable = [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }];

const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  images: {
    // Variants are pre-generated by scripts/optimize-images.mjs; no runtime optimizer.
    loader: 'custom',
    loaderFile: './src/lib/image-loader.ts',
    deviceSizes: [640, 828, 1080, 1280, 1600, 1920, 2560],
    imageSizes: [384],
  },
  async redirects() {
    return [
      { source: '/projects/profits', destination: '/work/profitz', permanent: true },
      { source: '/projects/profitz', destination: '/work/profitz', permanent: true },
      { source: '/projects/art-provenance', destination: '/work/artprovenance', permanent: true },
      { source: '/projects/artprovenance', destination: '/work/artprovenance', permanent: true },
      { source: '/work/art-provenance', destination: '/work/artprovenance', permanent: true },
      { source: '/projects/no-days-wasted', destination: '/work/no-days-wasted', permanent: true },
      { source: '/projects/sekundarac', destination: '/work/sekundarac', permanent: true },
      { source: '/projects/email-design', destination: '/work/email-design', permanent: true },
    ];
  },
  async headers() {
    return [
      ...(isProd ? [{ source: '/:path*', headers: securityHeaders }] : []),
      // Content-hashed file names, safe to cache forever
      { source: '/images/w/:path*', headers: immutable },
      { source: '/videos/:path*', headers: [{ key: 'Cache-Control', value: 'public, max-age=604800' }] },
    ];
  },
};

export default nextConfig;
